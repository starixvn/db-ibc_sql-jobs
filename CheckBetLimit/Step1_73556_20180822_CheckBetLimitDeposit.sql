INSERT INTO #supers(custid)
SELECT ci.custid
FROM CheckCustDB.dbo.custInfo ci WITH(NOLOCK) 
	INNER JOIN CheckCustDB.dbo.Dep_CustSuper s WITH(NOLOCK) ON ci.custid=s.custid
WHERE ci.roleid = 4 		
	AND ci.Enabled=1
	AND s.site NOT IN(SELECT site FROM #InactiveLicensee)
	AND ci.Currency<>20

WHILE (1 = 1)
BEGIN
	UPDATE TOP (1) #Supers
	SET isfinished = 1
		,@srecommend = custid			
	WHERE isfinished = 0
	
	IF @@ROWCOUNT = 0 BREAK	
		
	EXEC DBA_CheckBetLimit_Dep @srecommend=@srecommend,@RuleID=0	
END

DROP TABLE #supers
